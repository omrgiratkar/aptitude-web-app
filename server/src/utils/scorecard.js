import PDFDocument from "pdfkit";

export function createScorecardBuffer({ student, attempt }) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: "A4", margin: 52 });
      const chunks = [];
      doc.on("data", chunk => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      doc.rect(0, 0, doc.page.width, 130).fill("#14233B");
      doc.fillColor("#FFFFFF").fontSize(23).font("Helvetica-Bold").text("APTITUDE TEST", 52, 42);
      doc.fontSize(12).font("Helvetica").fillColor("#DDE8FF").text("Official Test Scorecard", 52, 78);
      doc.moveDown(4);
      doc.fillColor("#172033").fontSize(12).font("Helvetica-Bold").text("Student details", 52, 165);
      doc.moveTo(52, 188).lineTo(543, 188).strokeColor("#D9E1EC").stroke();
      const details = [
        ["Name", student.name],
        ["Email", student.email],
        ["Department", student.department || "—"],
        ["Test attempt ID", String(attempt._id)],
        ["Submitted at", attempt.submittedAt ? new Date(attempt.submittedAt).toLocaleString("en-IN") : "—"],
        ["Status", attempt.status]
      ];
      let y = 204;
      for (const [label, value] of details) {
        doc.font("Helvetica-Bold").fontSize(10).fillColor("#526174").text(label, 52, y, { width: 145 });
        doc.font("Helvetica").fontSize(10).fillColor("#172033").text(String(value), 205, y, { width: 335 });
        y += 27;
      }
      y += 12;
      doc.roundedRect(52, y, 491, 105, 10).fill("#EEF4FF");
      doc.fillColor("#14233B").font("Helvetica-Bold").fontSize(13).text("Final result", 72, y + 18);
      doc.fontSize(24).text(`${attempt.score} / ${attempt.total}`, 72, y + 43);
      const pct = attempt.total ? Math.round((attempt.score / attempt.total) * 100) : 0;
      doc.font("Helvetica").fontSize(12).fillColor("#2563EB").text(`${pct}%`, 350, y + 49);
      doc.fillColor("#526174").fontSize(9).text("Generated by the Aptitude Test Web Application", 52, 755);
      doc.end();
    } catch (err) { reject(err); }
  });
}
